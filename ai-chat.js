document.addEventListener("DOMContentLoaded", () => {
  const list = document.getElementById("chatList");
  const messages = document.getElementById("chatMessages");
  const selectedChat = new URLSearchParams(location.search).get("chat");
  let activeId = selectedChat;
  let chats = [];

  function renderMessages(items) {
    messages.innerHTML = items.length ? items.map(item => `<div class="chat-message ${item.role === "user" ? "user" : ""}">${escapeHtml(item.content)}</div>`).join("") : `<div class="empty-state"><strong>Say hello to your study assistant</strong><p>Ask for an explanation, example, or practice question.</p></div>`;
    messages.scrollTop = messages.scrollHeight;
  }
  async function render() {
    const [loadedChats, config] = await Promise.all([api("/chats"), api("/config")]);
    chats = loadedChats;
    document.getElementById("aiConfigNotice").textContent = config.aiChat ? "AI is configured. Responses are generated by the server-side provider." : "AI responses require OPENAI_API_KEY in the server environment. Messages are still saved securely.";
    list.innerHTML = chats.length ? chats.map(chat => `<a class="class-row ${String(chat.id) === String(activeId) ? "active" : ""}" href="ai-chat.html?chat=${chat.id}"><span class="row-main"><strong>${escapeHtml(chat.title)}</strong><small>${new Date(chat.updated_at).toLocaleDateString()}</small></span></a>`).join("") : `<div class="empty-state"><strong>No conversations yet</strong><p>Create one to get started.</p></div>`;
    if (activeId) {
      const current = chats.find(chat => String(chat.id) === String(activeId));
      if (!current) throw new Error("Conversation not found.");
      document.getElementById("chatTitle").textContent = current.title;
      renderMessages(await api(`/chats/${activeId}/messages`));
    }
  }
  document.getElementById("newChat").addEventListener("click", async () => {
    try {
      const chat = await api("/chats", { method: "POST", body: JSON.stringify({ title: "New conversation" }) });
      location.href = `ai-chat.html?chat=${chat.id}`;
    } catch (error) { document.getElementById("chatMessage").textContent = error.message; }
  });
  document.getElementById("chatForm").addEventListener("submit", async event => {
    event.preventDefault();
    const message = document.getElementById("chatMessage");
    const text = document.getElementById("chatInput").value.trim();
    if (!activeId) { message.textContent = "Create or choose a conversation first."; return; }
    const button = event.target.querySelector("button");
    button.disabled = true;
    message.textContent = "Sending…";
    try {
      const result = await api(`/chats/${activeId}/messages`, { method: "POST", body: JSON.stringify({ content: text }) });
      document.getElementById("chatInput").value = "";
      renderMessages(await api(`/chats/${activeId}/messages`));
      message.textContent = result.role === "assistant" ? "" : "Message saved.";
    } catch (error) {
      message.textContent = error.message;
      if (error.message.includes("message was saved")) renderMessages(await api(`/chats/${activeId}/messages`));
    } finally { button.disabled = false; }
  });
  render().catch(error => { document.getElementById("chatMessage").textContent = error.message; });
});
